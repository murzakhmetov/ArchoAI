#!/usr/bin/env bash
# Build the turntable firmware (turntable.ino) and flash it to the Arduino Uno on the Pi's USB port.
#
#   bash turntable/flash.sh            # build + flash (port found automatically, e.g. /dev/ttyACM0)
#   bash turntable/flash.sh build      # build only
#
# Uses PlatformIO in ~/.local/opt/platformio-venv (see server/esp32.sh). The first run downloads the
# AVR toolchain (~100 MB). The build folder is ~/.cache/archoai-turntable.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PIO="${PIO:-$HOME/.local/opt/platformio-venv/bin/pio}"
PROJECT="${ARCHOAI_TURNTABLE_BUILD:-$HOME/.cache/archoai-turntable}"
PORT="${TURNTABLE_PORT:-$(ls /dev/serial/by-id/*Arduino* /dev/serial/by-id/*USB_SER* /dev/ttyACM0 2>/dev/null | head -1 || true)}"
export PLATFORMIO_SETTING_ENABLE_TELEMETRY=no

[ -x "$PIO" ] || { echo "PlatformIO not found at $PIO"; exit 77; }
mkdir -p "$PROJECT/src"
cp "$REPO/turntable/turntable.ino" "$PROJECT/src/turntable.ino"
cat > "$PROJECT/platformio.ini" <<'EOF'
; Generated by ArchoAI turntable/flash.sh: Arduino Uno + CNC Shield V3
[env:uno]
platform = atmelavr
board = uno
framework = arduino
monitor_speed = 115200
EOF

if [ "${1:-}" = "build" ]; then
  "$PIO" run -d "$PROJECT"
else
  [ -n "$PORT" ] || { echo "no Arduino found on USB"; exit 1; }
  "$PIO" run -d "$PROJECT" -t upload --upload-port "$PORT"
fi
