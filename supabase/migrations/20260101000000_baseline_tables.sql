-- 20260101000000_baseline_tables.sql
--
-- Baseline for a FRESH Supabase project: the two tables the app and the ESP32 monitor used before any other
-- migration in this folder existed, with the policies that were live on 2026-11-13. It was rebuilt from the
-- live project's catalog (supabase/snapshots/2026-11-13_before.json), not from memory.
--
-- On the live project (wvhdhfddtusppjmsgmvn) every statement here is a no-op: the tables, the policies and
-- the realtime membership already exist, and the grants are only given to a table this file creates.
-- Idempotent, one transaction. It sorts before the other files on purpose: apply the migrations in
-- file-name order (see supabase/README.md).
--
-- NOT in here: the storage buckets (`supabase seed buckets` creates them from config.toml: a bucket is a
-- row that belongs to the Storage service) and everything that came later (migrations 000001 - 000008).
--
-- Kept exactly as found, on purpose:
--  * "Allow public insert" on artifacts lets the anon key insert artifact rows.
--  * the storage policies for artifact-images and 3d1 allow anonymous uploads.
--  * the four "Give users authenticated access to folder ..." policies are redundant dashboard-template
--    leftovers (the "Allow all for authenticated users ..." policies already cover them). They are
--    recreated only so that a fresh project matches the live one.
-- Tightening any of this is a product decision: see "Open decisions" in supabase/README.md.

begin;

do $$
begin
  if to_regclass('public.artifacts') is null then
    create table public.artifacts (
      id               uuid primary key default gen_random_uuid(),
      name             text not null,
      image_path       text not null default '',
      model_url        text,
      local_model_path text,
      created_at       timestamptz default now(),
      status           text default 'pending',
      type             text default 'Unknown',
      material         text default 'Unknown',
      era              text default 'Unknown',
      purpose          text default 'Unknown',
      condition        text default 'Stable',
      crack_percentage double precision default 0.0
    );
    -- Newer Supabase projects do not expose new tables to the Data API on their own.
    grant select, insert, update, delete on public.artifacts to anon, authenticated;
    grant all on public.artifacts to service_role;
  end if;

  if to_regclass('public.sensor_data') is null then
    create table public.sensor_data (
      id          bigint generated by default as identity primary key,
      temperature double precision not null,
      humidity    double precision not null,
      air_quality double precision not null,
      created_at  timestamptz default now()
    );
    grant select, insert, update, delete on public.sensor_data to anon, authenticated;
    grant all on public.sensor_data to service_role;
  end if;
end
$$;

alter table public.artifacts   enable row level security;
alter table public.sensor_data enable row level security;

-- Creates a policy only when no policy of that name exists on that table yet.
create or replace function pg_temp.ensure_policy(p_schema text, p_table text, p_name text, p_ddl text)
returns void
language plpgsql
as $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = p_schema and tablename = p_table and policyname = p_name
  ) then
    execute p_ddl;
  end if;
end
$$;

select pg_temp.ensure_policy('public', 'artifacts', 'Allow authenticated insert',
  $p$create policy "Allow authenticated insert" on public.artifacts
       for insert to authenticated with check (true)$p$);
select pg_temp.ensure_policy('public', 'artifacts', 'Allow authenticated read',
  $p$create policy "Allow authenticated read" on public.artifacts
       for select to authenticated using (true)$p$);
select pg_temp.ensure_policy('public', 'artifacts', 'Allow public insert',
  $p$create policy "Allow public insert" on public.artifacts
       for insert to public with check (true)$p$);
select pg_temp.ensure_policy('public', 'sensor_data', 'sensor_data_read_all',
  $p$create policy "sensor_data_read_all" on public.sensor_data
       for select to public using (true)$p$);

select pg_temp.ensure_policy('storage', 'objects', 'Allow all for authenticated users cljxsj_0',
  $p$create policy "Allow all for authenticated users cljxsj_0" on storage.objects
       for select to authenticated using (bucket_id = 'artifact-images')$p$);
select pg_temp.ensure_policy('storage', 'objects', 'Allow all for authenticated users cljxsj_1',
  $p$create policy "Allow all for authenticated users cljxsj_1" on storage.objects
       for insert to authenticated with check (bucket_id = 'artifact-images')$p$);
select pg_temp.ensure_policy('storage', 'objects', 'Allow all for authenticated users cljxsj_2',
  $p$create policy "Allow all for authenticated users cljxsj_2" on storage.objects
       for update to authenticated using (bucket_id = 'artifact-images')$p$);
select pg_temp.ensure_policy('storage', 'objects', 'Allow all for authenticated users cljxsj_3',
  $p$create policy "Allow all for authenticated users cljxsj_3" on storage.objects
       for delete to authenticated using (bucket_id = 'artifact-images')$p$);
select pg_temp.ensure_policy('storage', 'objects', 'Allow public insert into 3d1',
  $p$create policy "Allow public insert into 3d1" on storage.objects
       for insert to public with check (bucket_id = '3d1')$p$);
select pg_temp.ensure_policy('storage', 'objects', 'Allow public upload cljxsj_0',
  $p$create policy "Allow public upload cljxsj_0" on storage.objects
       for insert to public with check (bucket_id = 'artifact-images' and true)$p$);
select pg_temp.ensure_policy('storage', 'objects', 'Give users authenticated access to folder cljxsj_0',
  $p$create policy "Give users authenticated access to folder cljxsj_0" on storage.objects
       for select to authenticated
       using (bucket_id = 'artifact-images' and (storage.foldername(name))[1] = 'private'
              and auth.role() = 'authenticated')$p$);
select pg_temp.ensure_policy('storage', 'objects', 'Give users authenticated access to folder cljxsj_1',
  $p$create policy "Give users authenticated access to folder cljxsj_1" on storage.objects
       for insert to authenticated
       with check (bucket_id = 'artifact-images' and (storage.foldername(name))[1] = 'private'
                   and auth.role() = 'authenticated')$p$);
select pg_temp.ensure_policy('storage', 'objects', 'Give users authenticated access to folder cljxsj_2',
  $p$create policy "Give users authenticated access to folder cljxsj_2" on storage.objects
       for update to authenticated
       using (bucket_id = 'artifact-images' and (storage.foldername(name))[1] = 'private'
              and auth.role() = 'authenticated')$p$);
select pg_temp.ensure_policy('storage', 'objects', 'Give users authenticated access to folder cljxsj_3',
  $p$create policy "Give users authenticated access to folder cljxsj_3" on storage.objects
       for delete to authenticated
       using (bucket_id = 'artifact-images' and (storage.foldername(name))[1] = 'private'
              and auth.role() = 'authenticated')$p$);

-- The dashboard and the ESP32 monitor stream sensor_data over realtime.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (
       select 1 from pg_publication_tables
       where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'sensor_data'
     ) then
    alter publication supabase_realtime add table public.sensor_data;
  end if;
end
$$;

commit;

notify pgrst, 'reload schema';
