#!/usr/bin/env bash
# Build the ESP32 sensor firmware (monitoring.cpp) on this Pi with PlatformIO, or flash it to a board
# connected over USB. No PC and no Arduino IDE needed.
#
#   bash server/esp32.sh build                     # compile only
#   bash server/esp32.sh upload [/dev/ttyUSB0]     # compile and flash (the port is found automatically)
#   bash server/esp32.sh monitor [/dev/ttyUSB0]    # serial output of the board (115200 baud, Ctrl+C ends)
#
# PlatformIO lives in ~/.local/opt/platformio-venv (python3 -m venv ...; pip install platformio). The
# first build downloads the ESP32 toolchain (about 1.5 GB) into ~/.platformio; later builds take a minute.
# The build folder is ~/.cache/archoai-esp32 (outside the repository, so the Flutter and Node folders of
# the repository are never scanned).
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PIO="${PIO:-$HOME/.local/opt/platformio-venv/bin/pio}"
PROJECT="${ARCHOAI_ESP32_BUILD:-$HOME/.cache/archoai-esp32}"
export PLATFORMIO_SETTING_ENABLE_TELEMETRY=no

[ -x "$PIO" ] || { echo "PlatformIO not found at $PIO (python3 -m venv ~/.local/opt/platformio-venv && ~/.local/opt/platformio-venv/bin/pip install platformio)"; exit 77; }
cmp -s "$REPO/monitoring.cpp" "$REPO/scripts/monitoring.cpp" || echo "note: monitoring.cpp and scripts/monitoring.cpp differ; building the one in the repository root"

mkdir -p "$PROJECT/src"
cp "$REPO/monitoring.cpp" "$PROJECT/src/monitoring.cpp"
cat > "$PROJECT/platformio.ini" <<'EOF'
; Generated by ArchoAI server/esp32.sh: ESP32 DevKit (DHT11, MQ-135, soil moisture, DS18B20, SSD1306 OLED)
[env:esp32dev]
platform = espressif32
board = esp32dev
framework = arduino
monitor_speed = 115200
lib_deps =
  adafruit/Adafruit SSD1306
  adafruit/Adafruit GFX Library
  adafruit/DHT sensor library
  adafruit/Adafruit Unified Sensor
  paulstoffregen/OneWire
  milesburton/DallasTemperature
EOF

command="${1:-build}"
port=("${@:2}")
case "$command" in
  build)   "$PIO" run -d "$PROJECT" ;;
  upload)  "$PIO" run -d "$PROJECT" -t upload ${port:+--upload-port "${port[0]}"} ;;
  monitor) "$PIO" device monitor -d "$PROJECT" ${port:+--port "${port[0]}"} ;;
  *) echo "usage: $0 build | upload [port] | monitor [port]"; exit 2 ;;
esac
